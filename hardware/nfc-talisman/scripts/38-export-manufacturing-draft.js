const PANEL='4a4719695b24dc2b';
await eda.dmt_EditorControl.openDocument(PANEL);
await new Promise(r=>setTimeout(r,400));
if((await eda.dmt_SelectControl.getCurrentDocumentInfo())?.uuid!==PANEL)throw Error('Wrong panel document');
if(!await eda.pcb_Document.save())throw Error('Panel save failed');
const drc=await eda.pcb_Drc.check(true,false,true);
if(drc.length)throw Error('Panel DRC must have no findings for this draft export');
const files={};
const gerber=await eda.pcb_ManufactureData.getGerberFile('nfc-talisman-panel-draft',true,'mm',{integerNumber:3,decimalNumber:6},{metallicDrillingInformation:true,nonMetallicDrillingInformation:true,drillTable:true,flyingProbeTestingFile:false});
if(!gerber||!gerber.size)throw Error('Gerber unavailable');
const bytes=new Uint8Array(await gerber.arrayBuffer());
let binary='';
for(let i=0;i<bytes.length;i+=16384)binary+=String.fromCharCode(...bytes.subarray(i,i+16384));
files.gerber={name:gerber.name,size:gerber.size,base64:btoa(binary)};
const bom=await eda.pcb_ManufactureData.getBomFile('nfc-talisman-panel-bom-all','csv');
if(!bom||!bom.size)throw Error('BOM unavailable');
files.bom={name:bom.name,size:bom.size,text:await bom.text()};
const pnp=await eda.pcb_ManufactureData.getPickAndPlaceFile('nfc-talisman-panel-pnp-all','csv','mm');
if(!pnp||!pnp.size)throw Error('Pick and place unavailable');
files.pnp={name:pnp.name,size:pnp.size,text:await pnp.text()};
return {document:PANEL,status:'DRAFT_HORSE_ART_AND_CAM_PENDING',colorSilkscreenRequested:true,drc,files};
